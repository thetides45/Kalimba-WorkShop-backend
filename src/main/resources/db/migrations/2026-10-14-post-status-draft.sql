-- 2026-10-14 · 帖子状态新增「3 = 草稿」
--
-- 背景：post.status 原有三态 0 待审 / 1 正常 / 2 下架 —— 都是**管理视角**的状态。
--       本次新增 3 = 草稿，是**作者视角**的未发布态：仅作者本人（与管理员）可见，
--       不进列表（对他人）/ 详情（对他人）/ 搜索 / 热榜。
--
-- ⚠️ 草稿刻意**不复用 0**：0 已被 PostService.listPending()（管理端待审队列）
--    与 AdminService 的「待审帖子数」占用。混用会有两个后果：
--      ① 草稿混进管理端的审核队列；
--      ② 作者存一次草稿就收到「你的帖子已转为待审核」的站内通知。
--
-- 幂等：MODIFY COLUMN 只是重写列定义（含注释），重复执行结果一致，无需判存在性。
--       （与「加列」不同 —— 那个必须查 information_schema，见 2026-10-13 那份迁移。）

ALTER TABLE post
  MODIFY COLUMN status TINYINT NOT NULL DEFAULT 1
  COMMENT '0 审核 1 正常 2 下架 3 草稿（仅作者可见）';
